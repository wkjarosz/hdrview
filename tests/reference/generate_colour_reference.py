#!/usr/bin/env python3
"""Generate tests/colour_reference.h: reference values from colour-science for tests/test_colour_reference.cpp.

colour-science (https://www.colour-science.org) is an independent implementation of the standards HDRView's
color code follows, so its values check ours without a second copy of our own code. The tests compare against
the generated tables and need no Python; rerun this only to change what is sampled or to move to a newer
colour-science, and commit the result:

    python3 -m venv /tmp/colour-venv
    /tmp/colour-venv/bin/pip install colour-science==0.4.7 scipy
    /tmp/colour-venv/bin/python tests/reference/generate_colour_reference.py

Inputs stay where colour-science and HDRView agree on the convention: HDRView mirrors every transfer function
around the origin, colour-science extends most of them linearly, so negative inputs are left to HDRView's own
tests, but for sRGB, whose sign-extended form H.273 defines as sYCC.
"""

import pathlib
import warnings

warnings.filterwarnings("ignore")

import colour  # noqa: E402
import numpy as np  # noqa: E402

from colour.models.rgb.transfer_functions.itur_bt_2020 import CONSTANTS_BT2020_PRECISE  # noqa: E402
from colour.models.rgb.transfer_functions.itur_bt_2100 import gamma_function_BT2100_HLG  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parents[1] / "colour_reference.h"


def g(x):
    return f"{float(x):.9g}"


def scalar_table(name, xs, f):
    rows = ", ".join(f"{{{g(x)}, {g(f(x))}}}" for x in xs)
    return f"inline const Sample {name}[] = {{{rows}}};\n"


def triple(v):
    return "{" + ", ".join(g(c) for c in np.ravel(v)) + "}"


lines = []
emit = lines.append

emit("// Generated by tests/reference/generate_colour_reference.py from colour-science "
     f"{colour.__version__}; do not edit.\n")
emit("// clang-format off\n#pragma once\n\n#include \"colorspace.h\"\n\nnamespace colour_reference\n{\n\n")
emit("struct Sample { float in, out; };\n")
emit("struct ColorSample { float3 in, out; };\n\n")

# --- transfer functions -----------------------------------------------------------------------------------

# dense around piecewise transfer functions' breakpoints, where their segments nearly meet and a misplaced one shows
unit = sorted({0.0, 1e-5, 1e-4, 1e-3, 0.002, 0.0031308, 0.004, 0.01, 0.018053968510807, 0.02, 0.0228, 0.025, 0.03,
               0.04045, 0.05, 0.085, 0.0913, 0.095, 0.1, 0.18, 0.25, 0.5, 0.75, 0.9, 1.0})
extended = unit + [2.0, 10.0]
signed = sorted(unit + [-x for x in unit if x > 0])
nits = [0.0, 0.005, 0.1, 1.0, 10.0, 48.0, 80.0, 100.0, 203.0, 400.0, 1000.0, 2000.0, 4000.0, 10000.0]
logs = [x for x in unit if x >= 0.004] + [0.00316228, 0.0032, 0.005, 0.009, 0.011]

emit("// sRGB, IEC 61966-2-1, and its extension to negative values by odd symmetry, which H.273 defines as sYCC\n")
emit(scalar_table("sRGB_encode", extended, colour.models.eotf_inverse_sRGB))
emit(scalar_table("sRGB_decode", extended, colour.models.eotf_sRGB))
emit(scalar_table("sYCC_encode", signed, colour.models.oetf_H273_IEC61966_2))
emit(scalar_table("sYCC_decode", signed, colour.models.oetf_inverse_H273_IEC61966_2))

# colour-science's IEC 61966-2 function is the sRGB curve, so it has no IEC 61966-2-4 (xvYCC), which H.273
# defines as the BT.709 one sign-extended; HDRView's tests cover that through ITU_* below and odd symmetry.
emit("// BT.2020 with its exact constants, which BT.709 and BT.601 round, and which BT.2020's own tables give to\n")
emit("// four decimals\n")
emit(scalar_table("ITU_encode", unit, lambda x: colour.models.oetf_BT2020(x, constants=CONSTANTS_BT2020_PRECISE)))
emit(scalar_table("ITU_decode", unit,
                  lambda x: colour.models.oetf_inverse_BT2020(x, constants=CONSTANTS_BT2020_PRECISE)))

emit("// SMPTE ST 2084 (PQ), in cd/m^2\n")
emit(scalar_table("PQ_encode", nits, colour.models.eotf_inverse_ST2084))
emit(scalar_table("PQ_decode", unit, colour.models.eotf_ST2084))

emit("// BT.2100 HLG, scene-referred\n")
emit(scalar_table("HLG_OETF", unit, colour.models.oetf_BT2100_HLG))
emit(scalar_table("HLG_inverse_OETF", unit, colour.models.oetf_inverse_BT2100_HLG))
emit(scalar_table("HLG_system_gamma", [400.0, 1000.0, 2000.0, 4000.0], gamma_function_BT2100_HLG))

emit("// SMPTE 240M\n")
emit(scalar_table("ST240_encode", unit, colour.models.oetf_SMPTE240M))
emit(scalar_table("ST240_decode", unit, colour.models.eotf_SMPTE240M))

emit("// H.273's logarithmic transfer characteristics 9 and 10, above the floors where they clip\n")
emit(scalar_table("log100_encode", [x for x in logs if x >= 0.01], colour.models.oetf_H273_Log))
emit(scalar_table("log100_decode", unit[1:], colour.models.oetf_inverse_H273_Log))
emit(scalar_table("log100_sqrt10_encode", [x for x in logs if x >= 0.00316228], colour.models.oetf_H273_LogSqrt))
emit(scalar_table("log100_sqrt10_decode", unit[1:], colour.models.oetf_inverse_H273_LogSqrt))

emit("// SMPTE ST 428-1 (DCDM), in cd/m^2\n")
emit(scalar_table("DCI_P3_decode", unit, colour.models.eotf_DCDM))
emit(scalar_table("DCI_P3_encode", [0.0, 0.048, 0.48, 4.8, 10.0, 24.0, 48.0, 52.37],
                  colour.models.eotf_inverse_DCDM))

# The HLG EOTF depends on the color's luminance, so it takes whole colors; a gray one checks the scalar form.
emit("\n// BT.2100 HLG EOTF (BT.2100-2's black lift) for whole colors, in cd/m^2\n")
emit("struct HLGSample { float L_B, L_W; float3 in, out; };\n")
hlg_rows = []
for L_B, L_W in [(0.0, 1000.0), (0.0, 2000.0), (0.0, 400.0), (0.005, 1000.0)]:
    for rgb in [(0.5, 0.5, 0.5), (0.75, 0.75, 0.75), (0.2, 0.6, 0.9), (0.9, 0.1, 0.4), (1.0, 1.0, 1.0)]:
        out = colour.models.eotf_BT2100_HLG(np.array(rgb), L_B, L_W)
        hlg_rows.append(f"{{{g(L_B)}, {g(L_W)}, {triple(rgb)}, {triple(out)}}}")
emit("inline const HLGSample HLG_EOTF[] = {" + ", ".join(hlg_rows) + "};\n")

# --- color models -----------------------------------------------------------------------------------------

ill = colour.CCS_ILLUMINANTS["CIE 1931 2 Degree Standard Observer"]

emit("\n// CIE L*a*b*, for D65 and D50 reference whites given as xy with Y = 1\n")
emit("struct LabSample { float2 white_xy; float3 XYZ, Lab; };\n")
lab_rows = []
for wname in ["D65", "D50"]:
    wxy = ill[wname]
    for XYZ in [(0.95047, 1.0, 1.08883), (0.2, 0.3, 0.4), (0.05, 0.02, 0.1), (0.001, 0.002, 0.0015), (0.6, 0.5, 0.1)]:
        Lab = colour.XYZ_to_Lab(np.array(XYZ), wxy)
        lab_rows.append(f"{{{{{g(wxy[0])}, {g(wxy[1])}}}, {triple(XYZ)}, {triple(Lab)}}}")
emit("inline const LabSample Lab[] = {" + ", ".join(lab_rows) + "};\n")

emit("\n// HSL with hue as a turn in [0,1), for colors inside the unit cube that are not gray\n")
hsl_rows = []
for rgb in [(1.0, 0.0, 0.0), (0.2, 0.6, 0.9), (0.9, 0.1, 0.4), (0.3, 0.3, 0.1), (0.05, 0.9, 0.5), (0.6, 0.4, 0.8)]:
    hsl_rows.append(f"{{{triple(rgb)}, {triple(colour.RGB_to_HSL(np.array(rgb)))}}}")
emit("inline const ColorSample HSL[] = {" + ", ".join(hsl_rows) + "};\n")

# --- chromaticities, matrices and adaptation ---------------------------------------------------------------

gamuts = {
    "ColorGamut_sRGB_BT709": "sRGB",
    "ColorGamut_BT470M": "ITU-R BT.470 - 525",
    "ColorGamut_BT470BG": "ITU-R BT.470 - 625",
    "ColorGamut_SMPTE170M_240M": "SMPTE 240M",
    "ColorGamut_Film": "ITU-T H.273 - Generic Film",
    "ColorGamut_BT2020_2100": "ITU-R BT.2020",
    "ColorGamut_SMPTE428": "DCDM XYZ",
    "ColorGamut_DCI_P3_SMPTE431": "DCI-P3",
    "ColorGamut_Display_P3_SMPTE432": "Display P3",
    "ColorGamut_CICP_22": "ITU-T H.273 - 22 Unspecified",
    "ColorGamut_ACES_AP0": "ACES2065-1",
    "ColorGamut_ACEScg_AP1": "ACEScg",
    "ColorGamut_AdobeRGB": "Adobe RGB (1998)",
    "ColorGamut_ProPhotoRGB": "ProPhoto RGB",
}

emit("\n// each named gamut's primaries and white, and the RGB-to-XYZ matrix they define (row-major)\n")
emit("struct GamutSample { ColorGamut_ gamut; float2 red, green, blue, white; float RGB_to_XYZ[9]; };\n")
rows = []
for enum, name in gamuts.items():
    cs = colour.RGB_COLOURSPACES[name]
    p, w = cs.primaries, cs.whitepoint
    npm = colour.models.normalised_primary_matrix(p, w)
    xy = ", ".join(f"{{{g(c[0])}, {g(c[1])}}}" for c in [p[0], p[1], p[2], w])
    rows.append(f"{{{enum}, {xy}, {{{', '.join(g(v) for v in npm.ravel())}}}}}")
emit("inline const GamutSample gamuts[] = {" + ", ".join(rows) + "};\n")

whites = {f"WhitePoint_{k}": k for k in ["D50", "D55", "D65", "D75", "A", "B", "C", "E"]}
whites.update({f"WhitePoint_F{i}": f"FL{i}" for i in range(1, 13)})
whites.update({"WhitePoint_ACES": "ACES", "WhitePoint_DCI": "DCI-P3"})
emit("\n// the named white points' chromaticities (D93 has no CIE table entry, so it is left out)\n")
emit("struct WhiteSample { WhitePoint_ white_point; float2 xy; };\n")
emit("inline const WhiteSample white_points[] = {" +
     ", ".join(f"{{{e}, {{{g(ill[n][0])}, {g(ill[n][1])}}}}}" for e, n in whites.items()) + "};\n")

cats = {"AdaptationMethod_XYZScaling": "XYZ Scaling", "AdaptationMethod_Bradford": "Bradford",
        "AdaptationMethod_VonKries": "Von Kries", "AdaptationMethod_Identity": None}
pairs = [("ColorGamut_sRGB_BT709", "ColorGamut_ProPhotoRGB"), ("ColorGamut_sRGB_BT709", "ColorGamut_ACES_AP0"),
         ("ColorGamut_DCI_P3_SMPTE431", "ColorGamut_BT2020_2100"), ("ColorGamut_BT470M", "ColorGamut_sRGB_BT709"),
         ("ColorGamut_sRGB_BT709", "ColorGamut_BT2020_2100")]
emit("\n// RGB-to-RGB conversion matrices (row-major), between gamuts with differing whites, per adaptation\n")
emit("struct ConversionSample { ColorGamut_ src, dst; AdaptationMethod method; float M[9]; };\n")
rows = []
for src, dst in pairs:
    for cat_enum, cat in cats.items():
        # derived from the primaries, as HDRView does, rather than the matrices some standards publish rounded
        spaces = [colour.RGB_COLOURSPACES[gamuts[n]].copy() for n in (src, dst)]
        for cs in spaces:
            cs.use_derived_transformation_matrices(True)
        M = colour.matrix_RGB_to_RGB(spaces[0], spaces[1], chromatic_adaptation_transform=cat)
        rows.append(f"{{{src}, {dst}, {cat_enum}, {{{', '.join(g(v) for v in M.ravel())}}}}}")
emit("inline const ConversionSample conversions[] = {" + ", ".join(rows) + "};\n")

emit("\n// correlated color temperature to xy: Kang et al. 2002's fit, and the CIE daylight locus\n")
emit("struct CCTSample { float CCT; float2 xy; };\n")
emit("inline const CCTSample Kang2002[] = {" + ", ".join(
    f"{{{g(T)}, {{{g(v[0])}, {g(v[1])}}}}}" for T in [1667.0, 2000.0, 2856.0, 4000.0, 5003.0, 6504.0, 10000.0, 25000.0]
    for v in [colour.temperature.CCT_to_xy_Kang2002(T)]) + "};\n")
# The CIE's daylight formulas take temperatures on the c2 = 1.4380e-2 scale they were tabulated on; HDRView's
# daylight_to_xy() takes them on the current one, which is why the D illuminants are 5003 K, 6504 K and so on.
# The formulas end at 25000 K on the old scale, which is just below 25000 K on the new one.
rectify = 1.4387768775e-2 / 1.4380e-2
emit("inline const CCTSample CIE_daylight[] = {" + ", ".join(
    f"{{{g(T)}, {{{g(v[0])}, {g(v[1])}}}}}" for T in [4000.0, 5003.0, 5503.0, 6504.0, 7504.0, 10000.0, 24000.0]
    for v in [colour.temperature.CCT_to_xy_CIE_D(T * rectify)]) + "};\n")

emit("\n} // namespace colour_reference\n")
OUT.write_text("".join(lines))
print(f"wrote {OUT}")
